#include <stddef.h>

void	*ft_memcpy(void *dest, const void *src, size_t n)
{
	char	*tempdest;
	char	*tempsrc;
	size_t	i;

	if (dest == 0 && src == 0)
		return (0);
	tempdest = (char *)dest;
	tempsrc = (char *)src;
	i = 0;
	while (i < n)
	{
		tempdest[i] = tempsrc[i];
		i++;
	}
	return (dest);
}

